export function getCardTier(rating: number, isIcon: boolean): CardTier {
  if (isIcon || rating >= 93) return 'icon';
  if (rating >= 90) return 'master';
  if (rating >= 85) return 'elite';
  if (rating >= 75) return 'gold';
  return 'silver';
}

export function instantiatePlayerCard(base: BasePlayer, isTradable: boolean = true, initialRank: number = 0): PlayerCard {
  const tier = getCardTier(base.rating, base.league === 'Icons & Legends');
  const uniqueId = `card_${base.id}_${Date.now()}_${Math.random().toString(36).substring(2, 7)}`;
  
  return {
    id: uniqueId,
    basePlayerId: base.id,
    name: base.name,
    shortName: base.shortName,
    rating: base.rating,
    rank: initialRank,
    level: 0,
    position: base.position,
    secondaryPositions: base.secondaryPositions,
    preferredFoot: base.preferredFoot,
    skillMoves: base.skillMoves,
    weakFoot: base.weakFoot,
    league: base.league,
    club: base.club,
    nationality: base.nationality,
    nationFlag: base.nationFlag,
    stats: { ...base.stats },
    tier,
    isTradable,
    marketValue: base.marketBasePrice,
    specialTrait: base.specialTrait,
    acquiredDate: Date.now(),
  };
}

export function getPlayerCardCurrentRating(card: PlayerCard): number {
  return card.rating + card.rank;
}

export function getPlayerRankedStats(card: PlayerCard) {
  const boost = card.rank * 2 + Math.floor(card.level / 5);
  return {
    pace: Math.min(99, card.stats.pace + boost),
    shooting: Math.min(99, card.stats.shooting + boost),
    passing: Math.min(99, card.stats.passing + boost),
    dribbling: Math.min(99, card.stats.dribbling + boost),
    defending: Math.min(99, card.stats.defending + boost),
    physical: Math.min(99, card.stats.physical + boost),
  };
}
